const ROLE_LABELS = {
  leadership: { vi: "Ban lãnh đạo", en: "Leadership" },
  mi: { vi: "Phân tích thị trường", en: "Market Intelligence" },
  internal: { vi: "Người dùng nội bộ", en: "Internal user" },
};

let lang = "vi";
const listeners = new Set();

export function getLang() {
  return lang;
}

export function setLang(next) {
  if (next !== "vi" && next !== "en") return;
  lang = next;
  document.documentElement.lang = lang;
  listeners.forEach((listener) => listener(lang));
}

export function onLangChange(listener) {
  listeners.add(listener);
}

export function t(key, vars) {
  let text = (DICT[lang] && DICT[lang][key]) || (DICT.en && DICT.en[key]) || key;
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.replaceAll(`{${name}}`, String(value));
    });
  }
  return text;
}

export function roleLabel(role) {
  const entry = ROLE_LABELS[role];
  return entry ? entry[lang] || entry.en : role;
}
